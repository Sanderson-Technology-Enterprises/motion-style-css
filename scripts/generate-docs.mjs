import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import jsdoc2md from 'jsdoc-to-markdown';

/** Preserve generated Markdown line breaks without introducing Git whitespace errors. */
function cleanMarkdown(markdown) {
  return markdown.trim().replace(/[ \t]{2,}$/gm, '<br>');
}

/**
 * Generate one deterministic jsdoc2md reference per public export and reject drift.
 * @returns {Promise<void>} Resolves after all references have been written or checked.
 */
async function generateDocs() {
  const check = process.argv.includes('--check');
  const manifest = JSON.parse(await readFile('package.json', 'utf8'));
  const data = await jsdoc2md.getTemplateData({
    files: 'src/index.js',
    'no-cache': true,
  });
  const entries = data.filter(
    (item) =>
      !item.undocumented &&
      !item.ignore &&
      !item.access?.includes('private') &&
      ['function', 'constant'].includes(item.kind),
  );
  const expected = new Map();
  for (const entry of entries) {
    const rendered = await jsdoc2md.render({ data: [entry], 'no-cache': true });
    expected.set(
      `${entry.name}.md`,
      `<!-- Generated by jsdoc2md; do not edit. Version ${manifest.version}. -->\n\n${cleanMarkdown(rendered)}\n`,
    );
  }
  const types = await jsdoc2md.render({
    data: data.filter((item) => item.kind === 'typedef'),
    'no-cache': true,
  });
  expected.set(
    'types.md',
    `<!-- Generated by jsdoc2md; do not edit. Version ${manifest.version}. -->\n\n${cleanMarkdown(types)}\n`,
  );
  expected.set(
    'README.md',
    `<!-- Generated by jsdoc2md; do not edit. Version ${manifest.version}. -->\n\n# Public API\n\n${entries.map((item) => `- [${item.name}](./${item.name}.md)`).join('\n')}\n`,
  );
  await mkdir('docs/api', { recursive: true });
  const existing = await readdir('docs/api');
  for (const filename of existing) {
    if (!expected.has(filename))
      throw new Error(`Unexpected generated reference: ${filename}`);
  }
  for (const [filename, content] of expected) {
    const path = `docs/api/${filename}`;
    if (check) {
      const actual = await readFile(path, 'utf8').catch(() => '');
      if (actual !== content)
        throw new Error(`Generated documentation drift: ${path}`);
    } else await writeFile(path, content);
  }
  if (entries.length !== 7)
    throw new Error(
      `Expected seven documented public exports; found ${entries.length}`,
    );
  console.log(
    `${check ? 'Checked' : 'Generated'} ${entries.length} granular API references for ${manifest.version}`,
  );
}

await generateDocs();
